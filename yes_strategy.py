"""YES-стратегия — разворот после провала NO-подхода.

Прежняя логика (ставить NO, где Grok спорит с рынком) провалилась: Brier-вердикт
показал, что Grok проигрывает рынку, а механический NO против фаворитов давал
WR 9%. Оператор предложил обратное: не спорить с рынком, а плыть ПО нему —
ставить YES там, где рыночная цена в средней зоне (50-65% с 02.08, есть неэффективность)
и Grok СОГЛАСЕН по направлению.

Опора — калибровка: в корзине 0.6-0.8 Grok показал реальный YES 86%, т.е. в
средней-верхней зоне он надёжен и склонен недооценивать. Значит согласие Grok с
YES-направлением в зоне 50-65% — это сигнал недооценённого фаворита.

Важно: это ОТДЕЛЬНАЯ стратегия, валидируется с нуля своей выборкой. Она НЕ
наследует метрики NO-подхода.
"""
from __future__ import annotations
from typing import Optional

YES_MIN = 0.50          # ниже — монетка/андердог, нет опоры на фаворитизм
# Сужено 02.08.2026 с 0.70 по факту первых 13 резолвов: средняя цена входа 60.3c
# при WR 62% → безубыточный WR на 60c равен 60%, запас всего 2пп. Арифметика
# EV при WR 62%: вход 50c → +22% ROI, 60c → +2%, 70c → -12%. Всё дороже ~62c
# убыточно по определению, 0.65 оставлен как узкий буфер на случай роста WR
# при большей выборке.
# ВАЖНО: смена границы обнуляет сопоставимость — резолвы из зоны 50-70% и
# будущие из 50-65% это РАЗНЫЕ выборки, вердикт считать заново.
YES_MAX = 0.65          # выше — дорогой фаворит, цена съедает матожидание
GROK_YES_THRESHOLD = 0.50   # Grok должен быть склонён к YES (строго выше 0.5)


def yes_gate(market_yes: float) -> bool:
    """Структурный гейт YES-стратегии: рыночная цена YES в зоне YES_MIN-YES_MAX (50-65%)."""
    if market_yes is None:
        return False
    return YES_MIN <= market_yes <= YES_MAX


def yes_edge(market_yes: float, grok_yes: float) -> Optional[float]:
    """Edge YES-ставки при согласии направления.

    Условия: (1) цена в зоне 50-65%, (2) Grok склонён к YES (>0.5) — согласие по
    направлению с рынком. Достаточно согласия: не требуем Grok >= рынка, потому
    что edge держится на структурной недооценке средней зоны (подтверждается
    калибровкой), а не на превосходстве Grok над ценой.

    Возвращает edge (насколько Grok видит YES выше цены; минимум 0) или None,
    если условия не выполнены.
    """
    if market_yes is None or grok_yes is None:
        return None
    if not yes_gate(market_yes):
        return None
    if grok_yes <= GROK_YES_THRESHOLD:
        return None                       # Grok не согласен с YES-направлением
    # edge как согласованная недооценка: насколько Grok выше цены (>=0).
    # Даже при согласии-по-направлению без превосходства edge=0 — сигнал есть,
    # но слабый; сортировка потом поднимет те, где Grok заметно выше.
    return max(0.0, grok_yes - market_yes)


# Размер ставки — четверть Келли (политика §3). WR 62% — единственная измеренная
# оценка (n=13, широкая зона, до 02.08); при новом вердикте менять здесь.
YES_ASSUMED_WR = 0.62
KELLY_FRACTION = 0.25


def yes_kelly_stake(price: Optional[float], bankroll: float) -> int:
    """Четверть Келли для YES по цене price при WR YES_ASSUMED_WR, в целых $.

    f* = (p − price) / (1 − price). Округление вниз — при неуверенной WR
    ошибка в сторону меньшей ставки дешевле. 0 — ставка дороже безубытка.
    """
    try:
        price = float(price)
        bankroll = float(bankroll)
    except (TypeError, ValueError):
        return 0
    if not (0.0 < price < 1.0) or bankroll <= 0:
        return 0
    f = (YES_ASSUMED_WR - price) / (1.0 - price)
    if f <= 0:
        return 0
    return int(KELLY_FRACTION * f * bankroll)
